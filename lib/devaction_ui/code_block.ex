defmodule DevactionUI.CodeBlock do
  @moduledoc """
  A block of code in mono, given as the `code` attribute. `lang: :heex` colours it (components, slots,
  attributes, the special `:if`/`:for`/`phx-*` ones, strings, expressions, comments) and `lang: :elixir`
  colours Elixir, both through `DevactionUI.Highlight`; the code inside a HEEx `{}` or `<% %>` is coloured as
  Elixir too. `tone: :dark` is the ink block of a suggestion; `:risk` and `:ok` are the "your code" and
  "idiomatic" blocks of a lesson, tinted red and green; `:neutral` is the quiet tint. The dark block has fixed
  colours on purpose: it is a dark surface in both themes, and so is its syntax palette (the tinted tones take
  theirs from the tone). It keeps its own line breaks and scrolls sideways instead of widening the page.

  `lang` knows `:heex` and `:elixir`; any other code stays plain. With a `label` the block is a named region
  that the keyboard can focus, so a long line can be scrolled without a mouse. With `copy_label` a button
  copies the code (the `DevactionUI.CodeCopy` hook, so it needs an `id`; it stays hidden where the browser
  cannot write to the clipboard) and says `copied_label` for a moment.

  Lines. `line_numbers` draws a number before each line (generated by CSS, so copying the code does not copy
  them), `highlight_lines` marks lines by number or range (`[3, 5..7]`) and `diff` reads the first character of
  each line as a diff marker: `+` is an added line and `-` a removed one (the marker stays in the text, so the
  difference is not only a colour). The three work together and with `lang`.

  `class` and `rest` go to the `<pre>`, not to the container; `id` goes to the container.
  """
  use Phoenix.Component

  alias DevactionUI.{Highlight, Tone}

  attr :tone, :atom,
    values: [:dark, :risk, :ok, :neutral],
    default: :dark,
    doc:
      "`:dark` a suggestion, `:risk` the code to avoid, `:ok` the idiomatic one, `:neutral` quiet"

  attr :id, :string, default: nil

  attr :label, :string,
    default: nil,
    doc: "a mono caption above the block, and the name of its region for assistive technology"

  attr :copy_label, :string,
    default: nil,
    doc: "the name of the copy button; without it, no button"

  attr :copied_label, :string, default: nil, doc: "said for a moment after the copy"

  attr :lang, :atom,
    values: [nil, :heex, :elixir],
    default: nil,
    doc: "`:heex` colours the code by what each part of the template is, `:elixir` colours Elixir"

  attr :line_numbers, :boolean, default: false, doc: "a number before each line"

  attr :highlight_lines, :list,
    default: [],
    doc: "lines to mark, by number or range: `[3, 5..7]`"

  attr :diff, :boolean,
    default: false,
    doc: "lines that start with `+` are added, with `-` removed"

  attr :class, :any, default: nil

  attr :code, :string,
    required: true,
    doc: "the code as text: a `pre` keeps every space, so it never comes from a slot"

  attr :rest, :global
  slot :copy_icon, doc: "the icon of the copy button; without it the button shows `copy_label`"

  def code_block(%{copy_label: copy_label, id: nil}) when is_binary(copy_label),
    do: raise(ArgumentError, "code_block: `copy_label` needs an `id`")

  def code_block(assigns) do
    assigns = assign(assigns, :lined, lined?(assigns))

    ~H"""
    <div
      id={@id}
      phx-hook={@copy_label && "DevactionUI.CodeCopy"}
      class="flex min-w-0 flex-col gap-2"
    >
      <span
        :if={@label}
        class={["font-mono text-xs tracking-[0.08em] uppercase", label_class(@tone)]}
      >
        {@label}
      </span>
      <div class="relative flex min-w-0 flex-col">
        <button
          :if={@copy_label}
          type="button"
          hidden
          data-code-copy
          data-copied-label={@copied_label}
          class="absolute top-2 right-2 rounded-lg border border-line bg-card px-2 py-1 font-mono text-xs text-ink-2 outline-none hover:text-ink focus-visible:ring-4 focus-visible:ring-ink/10 data-[copied]:text-tag-ok-text"
        >
          {render_slot(@copy_icon)}<span class={@copy_icon != [] && "sr-only"}>{@copy_label}</span>
        </button>
        <span :if={@copy_label} data-code-status role="status" class="sr-only"></span>
        <pre
          role={@label && "region"}
          aria-label={@label}
          tabindex={@label && "0"}
          phx-no-curly-interpolation
          class={[
            "m-0 overflow-x-auto font-mono text-[13px] leading-[21px]",
            surface(@tone),
            @class
          ]}
          {@rest}
        ><code {gutter(@code, @lined)}><.lines :if={@lined} tone={@tone} lang={@lang} code={@code} line_numbers={@line_numbers} highlight_lines={@highlight_lines} diff={@diff} /><.tokens :if={!@lined} tone={@tone} lang={@lang} code={@code} /></code></pre>
      </div>
    </div>
    """
  end

  defp lined?(%{line_numbers: numbers, highlight_lines: marked, diff: diff}),
    do: numbers or marked != [] or diff

  defp gutter(_code, false), do: []

  defp gutter(code, true) do
    digits = code |> String.split("\n") |> length() |> Integer.digits() |> length()
    [style: "--code-gutter: #{digits}ch"]
  end

  attr :tone, :atom, required: true
  attr :lang, :atom, required: true
  attr :code, :string, required: true
  attr :line_numbers, :boolean, required: true
  attr :highlight_lines, :list, required: true
  attr :diff, :boolean, required: true

  defp lines(assigns) do
    lines = assigns.code |> tokenize(assigns.lang) |> Highlight.lines()
    assigns = assign(assigns, lines: lines, last: length(lines))

    ~H"""
    <span
      :for={{line, number} <- Enum.with_index(@lines, 1)}
      data-line={number}
      data-numbered={@line_numbers && ""}
      data-highlighted={marked?(@highlight_lines, number) && ""}
      data-diff={@diff && diff_kind(line)}
      class="code-line"
    ><span :for={{kind, text} <- line} class={kind_class(kind, @tone)}>{text}</span>{break(
      number,
      @last
    )}</span>
    """
  end

  attr :tone, :atom, required: true
  attr :lang, :atom, required: true
  attr :code, :string, required: true

  defp tokens(%{lang: nil} = assigns), do: ~H|{@code}|

  defp tokens(assigns) do
    assigns = assign(assigns, :tokens, tokenize(assigns.code, assigns.lang))

    ~H|<span :for={{kind, text} <- @tokens} class={kind_class(kind, @tone)}>{text}</span>|
  end

  defp tokenize(code, :heex), do: Highlight.heex(code)
  defp tokenize(code, :elixir), do: Highlight.elixir(code)
  defp tokenize(code, nil), do: [{:text, code}]

  defp break(last, last), do: ""
  defp break(_number, _last), do: "\n"

  defp marked?(highlight_lines, number), do: Enum.any?(highlight_lines, &in_marked?(&1, number))

  defp in_marked?(%Range{} = range, number), do: number in range
  defp in_marked?(number, number), do: true
  defp in_marked?(_other, _number), do: false

  defp diff_kind([{_kind, "+" <> _} | _]), do: "add"
  defp diff_kind([{_kind, "-" <> _} | _]), do: "del"
  defp diff_kind(_line), do: "context"

  defp kind_class(kind, :dark), do: dark_class(kind)
  defp kind_class(kind, _tone), do: tinted_class(kind)

  defp dark_class(:punct), do: "text-[#8B93A1]"
  defp dark_class(:html), do: "text-[#7AA2F7]"
  defp dark_class(:component), do: "text-[#7AA2F7]"
  defp dark_class(:slot), do: "text-[#A3B35A]"
  defp dark_class(:attr), do: "text-[#9CA3AF]"
  defp dark_class(:directive), do: "text-[#C4A7E7]"
  defp dark_class(:string), do: "text-[#E4E4E7]"
  defp dark_class(:expr), do: "text-[#E3A72F]"
  defp dark_class(:comment), do: "text-[#8B93A1] italic"
  defp dark_class(:keyword), do: "text-[#C4A7E7]"
  defp dark_class(:atom), do: "text-[#E3A72F]"
  defp dark_class(:number), do: "text-[#E3A72F]"
  defp dark_class(:module), do: "text-[#7AA2F7]"
  defp dark_class(:assign), do: "text-[#A3B35A]"
  defp dark_class(:text), do: nil

  defp tinted_class(kind) when kind in [:html, :component, :module], do: Tone.text(:info)
  defp tinted_class(kind) when kind in [:slot, :assign], do: Tone.text(:ok)
  defp tinted_class(kind) when kind in [:directive, :keyword], do: "text-learning"
  defp tinted_class(kind) when kind in [:expr, :atom, :number], do: Tone.text(:warn)
  defp tinted_class(kind) when kind in [:punct, :attr], do: "text-muted"
  defp tinted_class(:comment), do: "text-muted italic"
  defp tinted_class(_kind), do: nil

  defp surface(:dark), do: "rounded-[10px] bg-[#18181B] px-3.5 py-3 text-[#E4E4E7]"
  defp surface(tone), do: ["rounded-xl border p-3.5 text-ink", Tone.surface(tone)]

  defp label_class(:dark), do: "text-muted"
  defp label_class(tone), do: Tone.text(tone)
end
